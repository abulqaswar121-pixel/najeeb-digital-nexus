export function calculateRevenueSplit(
  amountNGN: number,
  amountUSD: number,
  isHybridPMTalent: boolean = false,
): RevenueSplitBreakdown {
  const adminMarginNGN = Math.round(amountNGN * 0.45);
  const adminMarginUSD = Math.round(amountUSD * 0.45);

  const pmFeeNGN = Math.round(amountNGN * 0.15);
  const pmFeeUSD = Math.round(amountUSD * 0.15);

  const talentPoolNGN = Math.round(amountNGN * 0.4);
  const talentPoolUSD = Math.round(amountUSD * 0.4);

  return {
    totalClientPaidNGN: amountNGN,
    totalClientPaidUSD: amountUSD,
    adminMarginPercent: 45,
    adminMarginNGN,
    adminMarginUSD,
    pmFeePercent: 15,
    pmFeeNGN,
    pmFeeUSD,
    talentPoolPercent: 40,
    talentPoolNGN,
    talentPoolUSD,
    isHybridDualRolePMTalent: isHybridPMTalent,
    ...(isHybridPMTalent
      ? {
          hybridTotalPayoutNGN: pmFeeNGN + talentPoolNGN,
          hybridTotalPayoutUSD: pmFeeUSD + talentPoolUSD,
        }
      : {}),
  };
}

